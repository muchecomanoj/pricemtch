-- A bulk-search row can now be saved one matched listing at a time, so a single
-- row produces several products. bulk_search_rows.saved_product_id holds one id
-- and cannot record that, which made every listing after the first look like the
-- first one being saved again.
--
-- One row per (row, listing) saved. Two things depend on it:
--   - saving the same card twice returns the product it already made, instead
--     of a second copy
--   - the rows API can report which cards are already saved, so the "Added as …"
--     markers survive a page reload rather than living only in the browser
--
-- saved_product_id is left in place and still written, so a caller that saves
-- without naming a listing behaves exactly as before.
CREATE TABLE bulk_search_row_saves (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at           TIMESTAMP(6),
    created_by           VARCHAR(255),
    updated_at           TIMESTAMP(6),
    updated_by           VARCHAR(255),
    row_id               BIGINT       NOT NULL,
    marketplace          VARCHAR(30)  NOT NULL,
    marketplace_item_id  VARCHAR(100) NOT NULL,
    product_id           BIGINT       NOT NULL,
    CONSTRAINT fk_row_save_row FOREIGN KEY (row_id)
        REFERENCES bulk_search_rows (id) ON DELETE CASCADE,
    -- The guard against duplicates, enforced here rather than only in code:
    -- two quick clicks on the same card arrive as two requests.
    CONSTRAINT uk_row_save_listing UNIQUE (row_id, marketplace, marketplace_item_id)
);

-- Every read is "what has this row already saved", to mark up its cards.
CREATE INDEX idx_row_save_row ON bulk_search_row_saves (row_id);

-- Deleting a product must not leave a save record pointing at nothing, which
-- would mark a card as saved and then fail to open it.
ALTER TABLE bulk_search_row_saves
    ADD CONSTRAINT fk_row_save_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE CASCADE;
